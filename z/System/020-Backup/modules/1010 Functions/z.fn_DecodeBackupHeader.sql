create or alter function z.fn_DecodeBackupHeader
(
	@HeaderJson nvarchar(max)
)
returns table
as
return
(
	-- JSON comes from the corresponding reader; binary properties are base64.
	select j.BackupName,
		j.BackupDescription,
		j.BackupType,
		j.ExpirationDate,
		j.Compressed,
		j.Position,
		j.DeviceType,
		j.UserName,
		j.ServerName,
		j.DatabaseName,
		j.DatabaseVersion,
		j.DatabaseCreationDate,
		j.BackupSize,
		j.FirstLSN,
		j.LastLSN,
		j.CheckpointLSN,
		j.DatabaseBackupLSN,
		j.BackupStartDate,
		j.BackupFinishDate,
		j.SortOrder,
		j.CodePage,
		j.UnicodeLocaleId,
		j.UnicodeComparisonStyle,
		j.CompatibilityLevel,
		j.SoftwareVendorId,
		j.SoftwareVersionMajor,
		j.SoftwareVersionMinor,
		j.SoftwareVersionBuild,
		j.MachineName,
		j.Flags,
		j.BindingID,
		j.RecoveryForkID,
		j.Collation,
		j.FamilyGUID,
		j.HasBulkLoggedData,
		j.IsSnapshot,
		j.IsReadOnly,
		j.IsSingleUser,
		j.HasBackupChecksums,
		j.IsDamaged,
		j.BeginsLogChain,
		j.HasIncompleteMetaData,
		j.IsForceOffline,
		j.IsCopyOnly,
		j.FirstRecoveryForkID,
		j.ForkPointLSN,
		j.RecoveryModel,
		j.DifferentialBaseLSN,
		j.DifferentialBaseGUID,
		j.BackupTypeDescription,
		j.BackupSetGUID,
		j.CompressedBackupSize,
		j.Containment,
		j.KeyAlgorithm,
		case when j.EncryptorThumbprint is null then null else x.XmlValue.value('xs:base64Binary(sql:column("j.EncryptorThumbprint"))', 'varbinary(20)') end EncryptorThumbprint,
		j.EncryptorType,
		j.LastValidRestoreTime,
		j.TimeZone,
		j.CompressionAlgorithm
	from openjson(@HeaderJson)
	with
	(
		BackupName nvarchar(128),
		BackupDescription nvarchar(255),
		BackupType smallint,
		ExpirationDate datetime,
		Compressed bit,
		Position smallint,
		DeviceType tinyint,
		UserName nvarchar(128),
		ServerName nvarchar(128),
		DatabaseName nvarchar(128),
		DatabaseVersion int,
		DatabaseCreationDate datetime,
		BackupSize numeric(20,0),
		FirstLSN numeric(25,0),
		LastLSN numeric(25,0),
		CheckpointLSN numeric(25,0),
		DatabaseBackupLSN numeric(25,0),
		BackupStartDate datetime,
		BackupFinishDate datetime,
		SortOrder smallint,
		CodePage smallint,
		UnicodeLocaleId int,
		UnicodeComparisonStyle int,
		CompatibilityLevel tinyint,
		SoftwareVendorId int,
		SoftwareVersionMajor int,
		SoftwareVersionMinor int,
		SoftwareVersionBuild int,
		MachineName nvarchar(128),
		Flags int,
		BindingID uniqueidentifier,
		RecoveryForkID uniqueidentifier,
		Collation nvarchar(128),
		FamilyGUID uniqueidentifier,
		HasBulkLoggedData bit,
		IsSnapshot bit,
		IsReadOnly bit,
		IsSingleUser bit,
		HasBackupChecksums bit,
		IsDamaged bit,
		BeginsLogChain bit,
		HasIncompleteMetaData bit,
		IsForceOffline bit,
		IsCopyOnly bit,
		FirstRecoveryForkID uniqueidentifier,
		ForkPointLSN numeric(25,0),
		RecoveryModel nvarchar(60),
		DifferentialBaseLSN numeric(25,0),
		DifferentialBaseGUID uniqueidentifier,
		BackupTypeDescription nvarchar(60),
		BackupSetGUID uniqueidentifier,
		CompressedBackupSize bigint,
		Containment tinyint,
		KeyAlgorithm nvarchar(32),
		EncryptorThumbprint nvarchar(max),
		EncryptorType nvarchar(32),
		LastValidRestoreTime datetime,
		TimeZone nvarchar(32),
		CompressionAlgorithm nvarchar(32)
	) j
		 cross apply (values(convert(xml, N''))) x(XmlValue)
);
GO
